def train_animation_state(frame):
    """Return (x_offset, visible) for the train at the given frame index.

    x_offset is added to TRAIN_HOME_X to get the train's current left edge.
    """
    t = frame % TRAIN_CYCLE_FRAMES
    if t < TRAIN_ENTER_END_FRAME:
        # Slide in from off-screen right (x_offset = W - TRAIN_HOME_X) to home (0).
        start = W - TRAIN_HOME_X
        p = t / TRAIN_ENTER_END_FRAME
        return int(round(start * (1.0 - ease_out_cubic(p)))), True
    if t < TRAIN_PARK_END_FRAME:
        return 0, True
    if t < TRAIN_EXIT_END_FRAME:
        # Slide left from home (0) to fully off-screen left (-(TRAIN_HOME_X + TRAIN_WIDTH)).
        end = -(TRAIN_HOME_X + TRAIN_WIDTH)
        span = TRAIN_EXIT_END_FRAME - TRAIN_PARK_END_FRAME
        p = (t - TRAIN_PARK_END_FRAME) / span
        return int(round(end * ease_in_cubic(p))), True
    return 0, False


def clamp(v, lo=0, hi=255):
    return max(lo, min(hi, int(v)))


def scale_color(col, amount):
    return (clamp(col[0] * amount), clamp(col[1] * amount), clamp(col[2] * amount))


def blend_color(col, target, amount):
    amount = max(0.0, min(1.0, amount))
    return (
        clamp(col[0] + (target[0] - col[0]) * amount),
        clamp(col[1] + (target[1] - col[1]) * amount),
        clamp(col[2] + (target[2] - col[2]) * amount),
    )


