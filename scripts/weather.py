def draw_lightning(c, frame):
    if (frame // 7) % 19 != 0:
        return
    bolt = (255, 246, 180)
    points = ((43, 4), (39, 10), (43, 10), (38, 18))
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        steps = max(abs(x1 - x0), abs(y1 - y0))
        for i in range(steps + 1):
            t = i / max(1, steps)
            px(c, int(x0 + (x1 - x0) * t), int(y0 + (y1 - y0) * t), bolt)


def foreground_tint_for(phase, condition):
    """Return the color transform applied to foreground pixels for the
    current phase + condition. Used by the ION train animation to keep the
    moving train and the empty-stop backdrop visually consistent with the
    rest of the scene."""
    if condition in (COND_RAIN, COND_STORM):
        return lambda col: tint_for_phase(foreground_storm(col), phase, "foreground")
    if phase == PHASE_NIGHT:
        return foreground_night
    if phase == PHASE_SUNRISE:
        return foreground_sunrise
    if phase == PHASE_SUNSET:
        return foreground_sunset
    return lambda col: col


def train_stop_tint_for(phase, condition, clouds):
    tint = foreground_tint_for(phase, condition)
    if phase == PHASE_NIGHT:
        return lambda col: NIGHT_SKY if is_source_sky_color(col) else tint(col)
    if phase == PHASE_DAY and clouds == CLOUD_OVERCAST and condition == COND_CLEAR:
        return lambda col: CLOUDY_DAY_SKY if is_source_sky_color(col) else tint(col)
    return tint


def draw_train_animation(c, frame, phase, condition, clouds):
    """Erase the parked train with the stop scenery, then overlay the moving
    train sprite at its current x offset. Both layers are tinted with the
    active foreground transform so they match the rest of the scene."""
    train_tint = foreground_tint_for(phase, condition)
    stop_tint = train_stop_tint_for(phase, condition, clouds)
    x_offset, visible = train_animation_state(frame)

    for row_offset, row in enumerate(TRAIN_STOP_SPANS):
        y = TRAIN_BBOX_Y0 + row_offset
        for dx, length, stop_col in row:
            hline(c, TRAIN_HOME_X + dx, y, length, stop_tint(stop_col))

    if visible:
        for dx, y, train_col, _stop_col in TRAIN_DIFF_ENTRIES:
            px(c, TRAIN_HOME_X + dx + x_offset, y, train_tint(train_col))


